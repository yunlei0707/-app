// 计算宝宝月龄对应的年龄段
export const getBabyAgeGroup = (birthDate) => {
  if (!birthDate) return '1';
  const months = (Date.now() - new Date(birthDate).getTime()) / (30 * 24 * 60 * 60 * 1000);
  if (months <= 3) return '1';
  if (months <= 6) return '2';
  if (months <= 12) return '3';
  return '4';
};

// 获取类型标签emoji
export const getTypeEmoji = (type) => {
  switch (type) {
    case 'photo': return '📷';
    case 'video': return '🎬';
    case 'audio': return '🎵';
    case 'diary': return '📝';
    default: return '📷';
  }
};

// 获取心情emoji
